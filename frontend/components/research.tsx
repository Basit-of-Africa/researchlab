export function BulletList({ items, empty = "—" }: { items?: any[]; empty?: string }) {
  if (!items?.length) return <p className="text-sm text-muted">{empty}</p>;
  return (
    <ul className="list-disc space-y-1 pl-5 text-sm">
      {items.map((x, i) => (
        <li key={i}>
          {typeof x === "string" ? <WithSourceRefs text={x} /> : <WithSourceRefs text={x.point ?? x.description ?? x.summary ?? x.issue ?? x.perspective ?? JSON.stringify(x)} />}
          {typeof x === "object" && x.sources?.length > 0 && <span className="ml-1 text-[11px] text-accent">[{x.sources.join(", ")}]</span>}
          {typeof x === "object" && x.severity && <Badge className="ml-1.5" tone={x.severity === "major" ? "danger" : x.severity === "moderate" ? "warn" : "neutral"}>{x.severity}</Badge>}
        </li>
      ))}
    </ul>
  );
}

/** Simple layered SVG diagram for a conceptual model {nodes, edges}. */
export function ConceptualModel({ model }: { model: { nodes?: { id: string; label: string; type?: string }[]; edges?: { source: string; target: string; label?: string; hypothesis_id?: string }[] } }) {
  const nodes = model?.nodes ?? [];
  const edges = model?.edges ?? [];
  if (!nodes.length) return null;
  // assign layers by longest path from sources
  const layer: Record<string, number> = {};
  nodes.forEach((n) => (layer[n.id] = 0));
  for (let i = 0; i < nodes.length; i++)
    edges.forEach((e) => {
      if (layer[e.target] !== undefined && layer[e.source] !== undefined) layer[e.target] = Math.max(layer[e.target], layer[e.source] + 1);
    });
  const cols: Record<number, string[]> = {};
  nodes.forEach((n) => (cols[layer[n.id]] ??= []).push(n.id));
  const W = 170, H = 46, GX = 90, GY = 26;
  const ncols = Object.keys(cols).length;
  const maxRows = Math.max(...Object.values(cols).map((c) => c.length));
  const pos: Record<string, { x: number; y: number }> = {};
  Object.entries(cols).forEach(([c, ids]) =>
    ids.forEach((id, r) => {
      const offset = ((maxRows - ids.length) * (H + GY)) / 2;
      pos[id] = { x: 10 + Number(c) * (W + GX), y: 10 + offset + r * (H + GY) };
    }),
  );
  const width = 20 + ncols * W + (ncols - 1) * GX;
  const height = 20 + maxRows * H + (maxRows - 1) * GY;
  const color = (t?: string) => (t === "outcome" ? "var(--ok)" : t === "moderator" ? "var(--warn)" : t === "mediator" ? "var(--ai)" : "var(--accent)");
  return (
    <svg viewBox={`0 0 ${width} ${height}`} className="w-full max-w-3xl" role="img" aria-label="Conceptual model">
      <defs>
        <marker id="arrow" viewBox="0 0 10 10" refX="9" refY="5" markerWidth="7" markerHeight="7" orient="auto-start-reverse">
          <path d="M 0 0 L 10 5 L 0 10 z" fill="var(--muted)" />
        </marker>
      </defs>
      {edges.map((e, i) => {
        const a = pos[e.source], b = pos[e.target];
        if (!a || !b) return null;
        const x1 = a.x + W, y1 = a.y + H / 2, x2 = b.x, y2 = b.y + H / 2;
        return (
          <g key={i}>
            <line x1={x1} y1={y1} x2={x2 - 2} y2={y2} stroke="var(--muted)" strokeWidth={1.3} markerEnd="url(#arrow)" />
            <text x={(x1 + x2) / 2} y={(y1 + y2) / 2 - 5} textAnchor="middle" fontSize="11" fill="var(--muted)">
              {[e.hypothesis_id, e.label].filter(Boolean).join(" ")}
            </text>
          </g>
        );
      })}
      {nodes.map((n) => (
        <g key={n.id}>
          <rect x={pos[n.id].x} y={pos[n.id].y} width={W} height={H} rx={6} fill="var(--surface)" stroke={color(n.type)} strokeWidth={1.5} />
          <foreignObject x={pos[n.id].x + 6} y={pos[n.id].y + 4} width={W - 12} height={H - 8}>
            <div style={{ fontSize: 12, lineHeight: "1.2", height: "100%", display: "flex", alignItems: "center", justifyContent: "center", textAlign: "center", color: "var(--text)" }}>
              {n.label}
            </div>
          </foreignObject>
        </g>
      ))}
    </svg>
  );
}
