export const CATEGORY_META: Record<KnowledgeCategory, { label: string; tone: "accent" | "ok" | "warn" | "neutral" | "ai"; help: string }> = {
  researcher_writing: { label: "Researcher writing", tone: "accent", help: "Your own written work" },
  established_position: { label: "Established position", tone: "ok", help: "A position you have explicitly approved" },
  provisional_opinion: { label: "Provisional opinion", tone: "warn", help: "Your tentative view — not settled" },
  external_evidence: { label: "External evidence", tone: "neutral", help: "Scholarly literature by others" },
  ai_interpretation: { label: "AI interpretation", tone: "ai", help: "Generated by ResearchLab — verify before relying on it" },
};

export function CategoryBadge({ category }: { category?: string }) {
  const m = CATEGORY_META[(category as KnowledgeCategory) ?? "external_evidence"];
  if (!m) return null;
  return (
    <Badge tone={m.tone} title={m.help}>
      {category === "ai_interpretation" && <Bot size={11} />}
      {m.label}
    </Badge>
  );
}

export function CategorySelect({ value, onChange, exclude = [] }: { value: string; onChange: (v: string) => void; exclude?: string[] }) {
  return (
    <select className="h-9 w-full rounded-md border border-border bg-surface px-3 text-sm" value={value} onChange={(e) => onChange(e.target.value)}>
      {Object.entries(CATEGORY_META)
        .filter(([k]) => !exclude.includes(k))
        .map(([k, m]) => (
          <option key={k} value={k}>
            {m.label} — {m.help}
          </option>
        ))}
    </select>
  );
}

export function VerificationBadge({ status }: { status?: string }) {
  const map: Record<string, ["ok" | "warn" | "danger" | "neutral", string]> = {
    verified: ["ok", "Verified"],
    mismatch: ["danger", "Metadata mismatch"],
    not_found: ["danger", "Not found in registries"],
    unverifiable: ["warn", "Registry unreachable"],
    incomplete: ["warn", "Insufficient metadata"],
    unverified: ["neutral", "Unverified"],
  };
  const [tone, label] = map[status ?? "unverified"] ?? ["neutral", status ?? "Unverified"];
  return <Badge tone={tone}>{label}</Badge>;
}

const TERMINAL = new Set(["succeeded", "failed", "paused", "awaiting_approval"]);

export function useJob(jobId: string | null | undefined, onDone?: (job: Job) => void) {
  const done = React.useRef(false);
  const { data, mutate } = useApi<Job>(jobId ? `/jobs/${jobId}` : null, {
    refreshInterval: (j) => (j && TERMINAL.has(j.status) ? 0 : 1500),
  });
  React.useEffect(() => {
    done.current = false;
  }, [jobId]);
  React.useEffect(() => {
    if (data && TERMINAL.has(data.status) && !done.current) {
      done.current = true;
      onDone?.(data);
    }
  }, [data, onDone]);
  return { job: data, mutate };
}

export function JobProgress({ jobId, onDone, compact }: { jobId: string | null | undefined; onDone?: (job: Job) => void; compact?: boolean }) {
  const { job, mutate } = useJob(jobId, onDone);
  const [err, setErr] = React.useState<unknown>(null);
  if (!jobId) return null;
  if (!job) return <div className="flex items-center gap-2 text-xs text-muted"><Spinner /> Starting…</div>;
  const act = async (a: "pause" | "resume") => {
    setErr(null);
    try {
      await api(`/jobs/${job.id}/${a}`, { method: "POST", body: {} });
      mutate();
    } catch (e) {
      setErr(e);
    }
  };
  const icon =
    job.status === "succeeded" ? <CheckCircle2 size={14} className="text-ok" /> :
    job.status === "failed" ? <XCircle size={14} className="text-danger" /> :
    job.status === "paused" || job.status === "awaiting_approval" ? <Pause size={14} className="text-warn" /> : <Spinner className="text-accent" />;
  return (
    <div className={cn("rounded-md border border-border bg-surface-2/60 px-3 py-2", compact && "py-1.5")}>
      <div className="flex flex-wrap items-center gap-2 text-xs">
        {icon}
        <span className="font-medium">{job.title}</span>
        <Badge>{job.status.replace("_", " ")}</Badge>
        {job.progress > 0 && job.progress < 1 && <span className="tabular-nums text-muted">{Math.round(job.progress * 100)}%</span>}
        <span className="ml-auto flex gap-1">
          {(job.status === "running" || job.status === "queued") && (
            <Button size="sm" variant="ghost" onClick={() => act("pause")}><Pause size={12} /> Pause</Button>
          )}
          {(job.status === "paused" || job.status === "failed") && (
            <Button size="sm" variant="outline" onClick={() => act("resume")}><Play size={12} /> Resume</Button>
          )}
          {job.status === "awaiting_approval" && (
            <Button size="sm" variant="primary" onClick={() => act("resume")}><CheckCircle2 size={12} /> Approve &amp; continue</Button>
          )}
        </span>
      </div>
      {job.status === "failed" && job.error && <p className="mt-1.5 text-xs text-danger">{job.error}</p>}
      {job.status === "queued" && job.error && <p className="mt-1.5 text-xs text-warn">Retrying after error: {job.error}</p>}
      {job.status === "awaiting_approval" && <p className="mt-1.5 text-xs text-warn">{job.result?.message}</p>}
      {!compact && job.steps && job.steps.length > 1 && (
        <ol className="mt-2 grid gap-0.5 text-[11px]">
          {job.steps.map((s) => (
            <li key={s.key} className="flex items-center gap-1.5">
              <span className={cn("h-1.5 w-1.5 rounded-full", s.status === "succeeded" ? "bg-ok" : s.status === "running" ? "bg-accent animate-pulse" : s.status === "failed" ? "bg-danger" : "bg-border")} />
              <span className={cn(s.status === "pending" && "text-muted")}>{s.label}</span>
            </li>
          ))}
        </ol>
      )}
      <ErrorNote error={err} />
    </div>
  );
}

export function SourceList({ sources, title = "Sources" }: { sources: Source[]; title?: string }) {
  if (!sources?.length) return <p className="text-xs text-muted">No sources were retrieved for this response.</p>;
  return (
    <details className="group">
      <summary className="cursor-pointer text-xs font-medium text-muted hover:text-text">{title} ({sources.length})</summary>
      <ol className="mt-2 space-y-1.5">
        {sources.map((s) => (
          <li key={s.sid} className="text-xs leading-snug">
            <span className="mr-1.5 rounded bg-surface-2 px-1 font-mono text-[10px]">{s.sid}</span>
            {s.document_id ? (
              <a className="hover:underline" href={`/knowledge/${s.document_id}`}>{s.label}</a>
            ) : (
              <span>{s.label}</span>
            )}
            {s.doi && (
              <a className="ml-1 text-accent hover:underline" href={`https://doi.org/${s.doi}`} target="_blank" rel="noreferrer">doi</a>
            )}
          </li>
        ))}
      </ol>
    </details>
  );
}

/** Renders [S#] markers as superscript references. */
export function WithSourceRefs({ text }: { text: string }) {
  const parts = text.split(/(\[S\d+(?:,\s*S\d+)*\])/g);
  return (
    <>
      {parts.map((p, i) =>
        /^\[S\d+/.test(p) ? (
          <sup key={i} className="mx-0.5 rounded bg-accent-soft px-1 text-[10px] font-medium text-accent">{p.slice(1, -1)}</sup>
        ) : (
          <React.Fragment key={i}>{p}</React.Fragment>
        ),
      )}
    </>
  );
}

export function Prose({ text }: { text: string }) {
  return (
    <div className="space-y-2 text-sm leading-relaxed">
      {text.split(/\n{2,}/).map((para, i) => (
        <p key={i} className="whitespace-pre-wrap"><WithSourceRefs text={para} /></p>
      ))}
    </div>
  );
}

type Decision = "approved" | "rejected" | "revised" | "regenerate" | "deferred" | "instruction";

/** The approval gate: the researcher — never the AI — approves. */
export function ApprovalBar({ onDecide, allow = ["approved", "rejected", "deferred"], busy }: {
  onDecide: (decision: Decision, rationale: string) => Promise<void> | void;
  allow?: Decision[];
  busy?: boolean;
}) {
  const [note, setNote] = React.useState("");
  const [open, setOpen] = React.useState(false);
  const labels: Record<Decision, string> = { approved: "Approve", rejected: "Reject", revised: "Mark revised", regenerate: "Regenerate", deferred: "Save for later", instruction: "Send instructions" };
  return (
    <div className="space-y-2">
      <div className="flex flex-wrap items-center gap-1.5">
        {allow.map((d) => (
          <Button key={d} size="sm" disabled={busy} variant={d === "approved" ? "primary" : d === "rejected" ? "danger" : "outline"}
            onClick={() => (d === "instruction" && !note ? setOpen(true) : onDecide(d, note))}>
            {d === "regenerate" && <RotateCw size={12} />}
            {labels[d]}
          </Button>
        ))}
        <button className="text-xs text-muted underline-offset-2 hover:underline" onClick={() => setOpen((o) => !o)}>
          {open ? "Hide note" : "Add rationale / instructions"}
        </button>
      </div>
      {open && <Textarea value={note} onChange={(e) => setNote(e.target.value)} placeholder="Your rationale or additional instructions (recorded in the decision log)" className="min-h-[60px]" />}
    </div>
  );
}

